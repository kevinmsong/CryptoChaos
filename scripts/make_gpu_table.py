"""LaTeX table and macros for the optional GPU diagnostic kernels (results/gpu).

    python scripts/make_gpu_table.py --gpu-dir results/gpu --out paper/generated/gpu
"""
from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--gpu-dir", type=Path, default=Path("results/gpu"))
    ap.add_argument("--out", type=Path, default=Path("paper/generated/gpu"))
    a = ap.parse_args()
    rows = list(csv.DictReader((a.gpu_dir / "metrics.csv").open(encoding="utf-8")))
    parity = json.loads((a.gpu_dir / "parity.json").read_text(encoding="utf-8"))
    env = json.loads((a.gpu_dir / "environment.json").read_text(encoding="utf-8"))
    sizes = sorted({int(r["bytes"]) for r in rows if r.get("bytes")})
    by = {(r["backend"], int(r["bytes"])): r for r in rows if r.get("bytes")}
    lines = ["% generated by scripts/make_gpu_table.py -- do not edit", r"\begin{tabular}{lrrrr}", r"\toprule",
             r"Payload & CPU & Triton kernel & Triton e2e & PyTorch e2e \\",
             r"\midrule"]
    for n in sizes:
        cpu, tri, tor = by.get(("cpu-numpy", n)), by.get(("gpu-triton", n)), by.get(("gpu-torch", n))
        label = f"{n // 2**20} MiB"
        lines.append(f"{label} & {float(cpu['end_to_end_ms']):.1f} & {float(tri['kernel_ms']):.2f} & "
                     f"{float(tri['end_to_end_ms']):.1f} & {float(tor['end_to_end_ms']):.1f} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}"]
    a.out.mkdir(parents=True, exist_ok=True)
    (a.out / "tab_gpu.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")
    dev = next((r["device"] for r in rows if r.get("device")), "unknown")
    torch_ver = (env.get("gpu", {}).get("torch") or {}).get("version", "unknown")
    big = max(sizes)
    speedup_e2e = float(by[("cpu-numpy", big)]["end_to_end_ms"]) / float(by[("gpu-triton", big)]["end_to_end_ms"])
    macros = {
        "Device": dev.replace("NVIDIA ", ""),
        "TorchVersion": torch_ver.replace("_", r"\_"),
        "TritonVersion": str(env.get("gpu", {}).get("triton", "unknown")),
        "ParityCases": str(len(parity)),
        "ParityExact": str(sum(1 for p in parity if p["hist_equal"] and p["diffs_equal"])),
        "LargestMiB": str(big // 2**20),
        "SpeedupEndToEnd": f"{speedup_e2e:.1f}",
    }
    (a.out / "macros.tex").write_text(
        "% generated by scripts/make_gpu_table.py -- do not edit\n"
        + "\n".join(f"\\newcommand{{\\ccGpu{k}}}{{{v}}}" for k, v in macros.items()) + "\n", encoding="utf-8")
    print(macros)
    return 0


if __name__ == "__main__":
    sys.exit(main())
